def add():
    db = SessionLocal()
    saved = 0
    skipped = 0
    try:
        for name, description in SHORT_WEAK:
            if db.query(RawWeakSignal).filter(RawWeakSignal.name == name).first():
                skipped += 1
                continue
            db.add(RawWeakSignal(
                name=name,
                description=description,
                source="short_weak",
                year=2026,
            ))
            saved += 1
        db.commit()
        logger.info(f"[short_weak] saved {saved}, skipped {skipped}, total {len(SHORT_WEAK)}")
    except Exception as e:
        db.rollback()
        logger.error(f"[short_weak] {e}")
    finally:
        db.close()


if __name__ == "__main__":
    add()
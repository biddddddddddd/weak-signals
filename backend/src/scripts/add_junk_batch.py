def add():
    db = SessionLocal()
    saved = 0
    skipped = 0
    try:
        for name, description in JUNK_BATCH:
            if db.query(RawJunkSignal).filter(RawJunkSignal.name == name).first():
                skipped += 1
                continue
            db.add(RawJunkSignal(
                name=name,
                description=description,
                category="pseudoscience_batch",
            ))
            saved += 1
        db.commit()
        logger.info(f"[junk batch] saved {saved}, skipped {skipped}, total {len(JUNK_BATCH)}")
    except Exception as e:
        db.rollback()
        logger.error(f"[junk batch] {e}")
    finally:
        db.close()


if __name__ == "__main__":
    add()
def add():
    db = SessionLocal()
    neg_saved = 0
    junk_saved = 0

    try:
        for name, desc in SHORT_NEGATIVE:
            if db.query(RawNegativeSignal).filter(RawNegativeSignal.name == name).first():
                continue
            db.add(RawNegativeSignal(
                name=name,
                description=desc,
                source="short_negative",
                year=2020,
            ))
            neg_saved += 1

        for name, desc in SHORT_JUNK:
            if db.query(RawJunkSignal).filter(RawJunkSignal.name == name).first():
                continue
            db.add(RawJunkSignal(
                name=name,
                description=desc,
                category="short_junk",
            ))
            junk_saved += 1

        db.commit()
        logger.info(f"[short_neg_junk] negative saved {neg_saved}, junk saved {junk_saved}")
    except Exception as e:
        db.rollback()
        logger.error(f"[short_neg_junk] {e}")
    finally:
        db.close()


if __name__ == "__main__":
    add()